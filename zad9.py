def vvod():
    """Спрашивает текст у пользователя."""
    return input("Введите текст со скобками: ")

def obrabotka(text):
    """Проверяет правильность расстановки скобок."""
    # Словарь, где ключ — закрывающая скобка, значение — открывающая
    pary = {")": "(", "]": "[", "}": "{"}
    
    # Стек для хранения открытых скобок
    stack = []

    for simvol in text:
        # Если это открывающая скобка — кладем в стек
        if simvol in "([{":
            stack.append(simvol)
            
        # Если это закрывающая скобка
        elif simvol in ")]}":
            # Если стек пуст, значит закрывать нечего (например, текст начинается с ")")
            if not stack:
                return False
            
            # Достаем последнюю открытую скобку из стека
            poslednyaya_otkrytaya = stack.pop()
            
            # Проверяем, совпадает ли она с текущей закрывающей
            # Например, если текущая ")", а из стека достали "[", это ошибка
            if poslednyaya_otkrytaya != pary[simvol]:
                return False

    # В конце стек должен быть пуст. Если в нем что-то осталось, 
    # значит, какую-то скобку не закрыли (например, "((").
    if len(stack) == 0:
        return True
    else:
        return False

def vyvod(rezultat):
    """Выводит результат проверки."""
    if rezultat:
        print("Скобки расставлены правильно (корректно).")
    else:
        print("Ошибка: скобки расставлены неправильно.")

# Запуск
tekst = vvod()
res = obrabotka(tekst)
vyvod(res)